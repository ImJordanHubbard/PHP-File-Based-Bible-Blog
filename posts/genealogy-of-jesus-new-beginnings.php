<h2>The Genealogy of Jesus: New Beginnings, Promise, and Design</h2>

<blockquote>The book of the genealogy of Jesus Christ, the son of David, the son of Abraham - Matthew 1:1</blockquote>

<p>How someone introduces a text can reveal a great deal about the message they intend to communicate. Genealogies are often skimmed over, considered dull, or difficult to follow, yet Matthew’s introduction is deliberately structured.</p>

<p>In this article, we will explore the opening verse of Matthew’s Gospel and the structure of the genealogy of Jesus Christ.</p>

<h2>A New Beginning</h2>

<p>Matthew quotes the Old Testament more than any other New Testament writer, so it should come as no surprise that the opening line of his Gospel echoes a Genesis-style introduction:</p>

<ul>

  <li><em>This is the history of the generations...</em> - Genesis 2:4</li>

  <li><em>This is the book of the generations of Adam...</em> - Genesis 5:1</li>

  <li><em>The book of the genealogy of Jesus Christ...</em> - Matthew 1:1</li>

</ul>

<p>By using the phrase <em>book of the genealogy</em> (biblos geneseos), mirroring the language of the Septuagint in Genesis 2:4 and 5:1, Matthew appears to frame Jesus’ story in creation terms, rooting it in the work God began in Genesis.</p>

<p>His phrasing suggests that Jesus’ story is not merely a continuation of God’s plan. Rather, it marks a new beginning, pointing toward the new covenant.</p>

<h2>Covenant and Promise</h2>

<blockquote>The son of David, the son of Abraham - Matthew 1:1</blockquote>

<p>The order of Matthew 1:1 appears deliberate. By naming David first, Matthew presents Jesus as the royal Son, the promised king from David’s line, before tracing the broader covenant promise through Abraham.</p>

<p>Matthew establishes Jesus’ credibility in two clear ways:</p>

<ul>

  <li><strong>First,</strong> through his kingly line, fulfilling the covenant promises God made to David in 2 Samuel 7:12-16. While the throne is initially given to Solomon, the covenant extends beyond him to an eternal king, ultimately fulfilled in Jesus.</li>

  <li><strong>Second,</strong> by fulfilling the promises made to Abraham, such as the promise in Genesis 22:15-18, given after Abraham’s willingness to sacrifice his son Isaac. This promise identifies Abraham’s offspring as the means through whom blessing would come to all nations, a promise Matthew presents as fulfilled in Christ.</li>

</ul>

<p>By linking Jesus to David and Abraham, Matthew’s genealogy can reasonably be understood as presenting Jesus as the Messiah, rather than functioning as a mere historical record.</p>

<h2>The 14-14-14 Structure</h2>

<p>Matthew’s introduction also draws attention to the genealogy’s 14-14-14 structure, which appears to carry deliberate theological significance.</p>

<p>Matthew divides Jesus’ genealogy into three distinct periods of Israel’s history:</p>

<ul>

  <li><strong>Abraham-David:</strong> the patriarchal period and the establishment of God’s promises</li>

  <li><strong>David-Babylon:</strong> the monarchy, with certain kings omitted to maintain the pattern of fourteen, highlighting Jesus’ legal claim to David’s throne through Joseph</li>

  <li><strong>Babylon-Christ:</strong> the exile and post-exilic period, culminating in the arrival of Christ</li>

</ul>

<p>A common understanding among commentators is that Matthew intentionally structured the genealogy into three groups of fourteen to emphasise Jesus’ Davidic identity. In Hebrew, the letters of David’s name (Dalet 4, Vav 6, Dalet 4) sum to fourteen, supporting the view that Matthew is reinforcing the Messiah’s royal lineage.</p>

<p>Matthew’s 14-14-14 arrangement draws attention to the shape of Israel’s history, presenting it as ordered and purposeful, leading toward its fulfilment in Christ.</p>

