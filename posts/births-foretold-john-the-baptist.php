<p>Luke’s Gospel is unique in that it records the events leading up to the births of John the Baptist and Jesus Christ.</p>  

  

<p>The other Gospels introduce John the Baptist at the start of Jesus’ public ministry, focusing on his preaching and baptism. Luke, by contrast, introduces John earlier, beginning with the circumstances surrounding his birth.</p>  

  

<p>In this article, I focus on Luke 1:5–25, the account in which the birth of John the Baptist is foretold.</p>  

  

<h2>John the Baptist’s Priestly Background</h2>  

  

<p>The first observation from this account is that John the Baptist comes from a priestly background.</p>  

  

<p>Zechariah was a priest of the division of Abijah, the eighth division established under David (1 Chronicles 24:1–31). Elizabeth, the wife of Zechariah and the mother of John the Baptist, was one of the daughters of Aaron, placing her within the Aaronic priestly lineage.</p>  

  

<p>Aaron was the brother of Moses and the first high priest of Israel, appointed along with his sons to serve as priests (Exodus 28:1).</p>  

  

<p>Despite this lineage, John the Baptist is not presented as serving as a priest. Instead, Luke portrays him as one who prepares the way for the Lord.</p>  

  

<h2>Elizabeth and Zechariah Compared with Abraham and Sarah</h2>  

  

<p>Elizabeth and Zechariah closely parallel Abraham and Sarah.</p>  

  

<p>Sarah, the wife of Abraham, is described as advanced in years and unable to bear children prior to the birth of Isaac (Genesis 18). Elizabeth is likewise described as advanced in years and childless (Luke 1:7).</p>   

  

<p>In Genesis, the birth of Isaac is announced by angelic messengers. In Luke’s account, the angel Gabriel announces that Elizabeth will bear a son named John (Luke 1:13).</p>  

  

<p>Sarah responds by laughing at the prospect of bearing a child (Genesis 18:12), while Zechariah responds by asking how he can be certain of what he has heard (Luke 1:18).</p>  

  

<p>These parallels place the announcement of John’s birth alongside earlier moments in Scripture where God acts in seemingly impossible circumstances.</p>  

  

<h2>John the Baptist and Elijah</h2>  

  

<p>Luke 1:17 describes John as going before the Lord “in the spirit and power of Elijah.” This language echoes the closing verses of Malachi, where Elijah is promised as a forerunner before the day of the Lord.</p>  

  

<p>Malachi 4:6 describes his work as turning the hearts of fathers to their children. Luke 1:17 uses similar language to describe John’s role, turning hearts and leading the disobedient toward wisdom.</p>  

  

<p>Where Malachi presents Elijah’s sending in relation to the day of the Lord, Luke describes John’s role as preparing a people for the Lord.</p>  

  

<p>Luke also notes that John is to abstain from wine and strong drink from birth (Luke 1:15). This language recalls earlier figures set apart from birth, such as Samson (Judges 13), and resembles consecration practices described in Numbers 6.</p>  

  

<h2>The Sign Given to Zechariah</h2>  

  

<p>When Zechariah leaves the temple unable to speak, those present conclude that he has seen a vision (Luke 1:21–22). After completing his time of service, Zechariah returns home and Elizabeth becomes pregnant.</p>  

  

<p>Elizabeth remains in seclusion for five months and interprets these events in her own words: “The Lord has done this for me. In these days he has shown his favour and taken away my disgrace among the people” (Luke 1:23–25).</p>  

  

<p>Although Luke does not explain the nature of this disgrace, childlessness in Jewish society was often experienced as a source of public shame, frequently interpreted by others as judgement from God, even though Scripture repeatedly records God working through such circumstances.</p>  

  

<p>This pattern is seen in Sarah (Genesis 18), Rachel (Genesis 30:1), and Hannah (1 Samuel 1:6–7), whose barrenness is associated with distress but later becomes the setting for God’s intervention.</p>  

  

