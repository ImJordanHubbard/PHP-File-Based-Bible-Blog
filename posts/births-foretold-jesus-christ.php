<p>Every year at Christmas, the birth of Christ is celebrated through accounts of the nativity scene, the magi, and the shepherds. What is less often considered are the events that precede Christ’s birth.</p>

<p>In this article, I focus on the event recorded in Luke 1:26–38, commonly known as the annunciation of Jesus Christ, in which the birth of Jesus is foretold.</p>

<h2>The Setting: Nazareth</h2>

<p>The account opens with God sending the angel Gabriel to a city in Galilee called Nazareth, to the home of Mary.</p>

<p>Nazareth was a small city in Galilee, believed to have had around 300 inhabitants at the time of Christ.</p>

<p>Nazareth was distant from Jerusalem and outside Judea’s religious centre, and it was not regarded as significant.</p>

<p>When Philip tells Nathanael that they have found the Messiah, Nathanael replies, “Can anything good come out of Nazareth?” (John 1:45–46).</p>

<p>The Messiah is being identified with a place that carried no reputation.</p>

<h2>The Virgin Mary</h2>

<p>The Bible does not say much about the background of Mary. When the angel Gabriel is sent to her, she is described as a virgin betrothed to Joseph.</p>

<p>The Greek word translated “virgin” in this passage is <em>parthenos</em>. This term, together with the Hebrew word <em>ʿalmâ</em> in Isaiah 7:14, a passage cited as prophecy of the virgin birth, has prompted discussion because of its association with both virginity and a young woman.</p>

<p>Later in the account, when Mary is told that she will conceive and bear a son, she asks how this will be possible, given that she is a virgin. Her question clarifies how Luke presents her, as one who has known no man.</p>

<p>Being betrothed to Joseph, a status that preceded marriage yet was as binding as marriage itself, would have made Mary’s pregnancy not only unexpected but problematic. Matthew’s Gospel later records Joseph’s intention to divorce her quietly, highlighting the seriousness of the situation.</p>

<h2>The Angel’s Greeting to Mary, the Favoured One</h2>

<p>A visitation from an angel would have been unexpected, and Mary is described as being troubled by the greeting (Luke 1:29).</p>

<p>Gabriel reassures her and says that she has found favour, <em>charis</em>, which means grace.</p>

<p>Mary’s favour with God is not presented as being connected to her background. She is a Jewish girl from an insignificant place, far from Jerusalem, and betrothed to a tradesman.</p>

<p>Elizabeth, by contrast, is married to a priest and is herself from the Aaronic priestly line, which by human standards would appear more significant. The contrast highlights that favour is not tied to status.</p>

<h2>Jesus, Son of the Most High</h2>

<p>Gabriel continues by telling Mary that she will conceive and bear a son, and that his name will be Jesus.</p>

<p>In Luke 1:32–33, Gabriel declares that this child will be called the Son of the Most High and will reign over the house of Jacob forever.</p>

<p>From the time of Melchizedek, king of Salem, in Genesis 14:18–20, Yahweh is referred to as the Most High. Luke’s wording aligns this title with Jesus, presenting a claim about his identity that goes beyond that of a merely human ruler.</p>

<p>The declaration that Jesus will reign over the house of Jacob forever draws on Old Testament expectations of a coming king. Isaiah 9:6–7 speaks of a ruler from David’s line whose reign would be lasting and righteous.</p>

<p>During the exile, when the Davidic monarchy had failed and the nation was in ruin, Jeremiah 23:5–6 renews that hope by promising a future king, a righteous Branch, who would restore and rule God’s people.</p>

<p>Luke also states that God will give Jesus “the throne of his father David” and that “of his kingdom there will be no end.” This language places the announcement within Israel’s historical and covenantal framework, presenting Jesus as the continuation and fulfilment of the Davidic kingship.</p>

<h2>Mary’s Response to Gabriel</h2>

<p>Mary, like Zechariah earlier in Luke 1 and Sarah in Genesis, responds by asking how this can be, given her circumstances.</p>

<p>Gabriel answers in Luke 1:35, explaining that the Holy Spirit will come upon her and that the power of the Most High will overshadow her, and therefore the child to be born will be called holy, the Son of God.</p>

<p>Gabriel then points to Elizabeth’s pregnancy as evidence of God’s power, concluding with the statement, “For nothing is impossible with God.”</p>

<p>Mary responds by submitting herself to God’s word, saying, “Behold, I am a servant of the Lord; let it be to me according to your word.”</p>

